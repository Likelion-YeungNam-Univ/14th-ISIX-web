/**
 * 화면에 부를 아바타 이름.
 *
 * 사용자가 이름을 붙였으면 그것을, 아니면 순번으로 부릅니다. 순번은 저장된
 * 값이 아니라 목록에서의 위치라 앞의 것을 지우면 뒤 번호가 당겨집니다.
 * 이름을 붙이면 그 문제가 사라지는 것이 이름 기능의 쓸모이기도 합니다.
 *
 * 아바타를 부르는 곳이 세 군데(아바타 페이지 · 피팅룸 아바타 시트 ·
 * 홈 의류 카드)라 한 곳에 모읍니다. 흩어져 있으면 이름을 바꿨는데 어떤
 * 화면에서는 그대로 순번으로 남습니다.
 *
 * fallback 은 화면마다 문구가 달라서 받습니다. 피팅룸은 "나의 아바타 1",
 * 나머지는 "아바타 1" 입니다.
 */
export const avatarDisplayName = (
  item: { name?: string | null },
  index: number,
  fallbackPrefix = '아바타',
) => item.name?.trim() || `${fallbackPrefix} ${index + 1}`;
